const SAMPLES_PER_START = 4;

let cached = null;

/**
 * 拼出这次启动用的人设。
 *
 * 抽样只在进程里做一次，之后复用：系统提示是上下文缓存的**前缀**，
 * 每次都重抽等于每句话都按未命中价算（贵 10 倍以上）。
 */
function defaultPersona() {
  if (cached) return cached;
  const multi = [];
  const single = [];
  for (const s of SAMPLES) (s.includes('\n') ? multi : single).push(s);
  const take = (arr) => arr.splice(Math.floor(Math.random() * arr.length), 1)[0];
  const picked = [];
  // 多段固定抽 2 组、单段抽 2 组（不够再互相补）：
  // 全靠随机的话有近四成概率整轮抽不到多段样例，模型就只学会"一句打发"。
  while (picked.length < SAMPLES_PER_START) {
    if (multi.length && (picked.filter((s) => s.includes('\n')).length < 2 || !single.length)) picked.push(take(multi));
    else if (single.length) picked.push(take(single));
    else if (multi.length) picked.push(take(multi));
    else break;
  }
  cached = HEAD.join('\n') + '\n' + MUST.join('\n') + '\n' + picked.join('\n') + '\n' + TAIL.join('\n');
  return cached;
}

/** 测试用：清掉抽样缓存，让下次重新抽。 */
function resetPersonaCache() {
  cached = null;
}

module.exports = { defaultPersona, resetPersonaCache, HEAD, SAMPLES, MUST, TAIL };
